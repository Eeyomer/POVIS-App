// Writes src/app/core/environment/availability.ts from the IS_AVAILABLE env var.
// Anything other than "false" (case-insensitive) counts as available.
import { writeFileSync } from 'node:fs';

const isAvailable = String(process.env.IS_AVAILABLE ?? 'true').trim().toLowerCase() !== 'false';
const target = new URL('../src/app/core/environment/availability.ts', import.meta.url);

writeFileSync(
  target,
  `// Generated by scripts/set-availability.mjs from the IS_AVAILABLE env var. Do not edit.\nexport const isAvailable = ${isAvailable};\n`,
);
console.log(`[set-availability] isAvailable = ${isAvailable}`);
