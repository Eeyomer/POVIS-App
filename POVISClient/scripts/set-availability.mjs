// Writes src/app/core/environment/availability.ts from environment variables.
//   IS_AVAILABLE     - anything other than "false" (case-insensitive) counts as available.
//   IS_STORAGE_FULL  - "true" (case-insensitive) blocks every "add" and shows the storage modal; default off.
import { writeFileSync } from 'node:fs';

const flag = (name) => String(process.env[name] ?? '').trim().toLowerCase();
const isAvailable = (flag('IS_AVAILABLE') || 'true') !== 'false';
const isStorageFull = flag('IS_STORAGE_FULL') === 'true';
const target = new URL('../src/app/core/environment/availability.ts', import.meta.url);

writeFileSync(
  target,
  `// Generated by scripts/set-availability.mjs from the IS_AVAILABLE and IS_STORAGE_FULL env vars. Do not edit.\nexport const isAvailable = ${isAvailable};\nexport const isStorageFull = ${isStorageFull};\n`,
);
console.log(`[set-availability] isAvailable = ${isAvailable}, isStorageFull = ${isStorageFull}`);
